import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { Script } from 'node:vm';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = resolve(root, 'node_modules/@noble/ciphers');
const metadata = JSON.parse(readFileSync(resolve(packageDir, 'package.json'), 'utf8'));
assert.equal(metadata.version, '2.4.0', 'Crypto vendor must use the reviewed pinned version');
const hashesDir = resolve(root, 'node_modules/@noble/hashes');
const hashesMetadata = JSON.parse(readFileSync(resolve(hashesDir, 'package.json'), 'utf8'));
assert.equal(hashesMetadata.version, '2.0.1', 'Password vendor must use the reviewed pinned version');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['scripts/crypto-vendor-entry.mjs'],
  bundle: true,
  format: 'iife',
  globalName: 'TthcCipher',
  platform: 'neutral',
  target: 'es2020',
  treeShaking: true,
  minify: false,
  legalComments: 'inline',
  write: false,
  banner: { js: '// Generated by scripts/build-crypto-vendor.mjs. Do not edit.\n// @noble/ciphers 2.4.0, AES-SIV RFC 5297; @noble/hashes 2.0.1, scrypt RFC 7914.\n// MIT licenses: docs/vendor/noble-ciphers-LICENSE.txt and noble-hashes-LICENSE.txt.\n// Bundled locally; no CDN, network provider, Node APIs, or browser crypto APIs.' }
});
const source = result.outputFiles[0].text;
new Script(source, { filename: 'CryptoVendor.gs' });
assert.ok(!/\b(?:import|require)\s*\(|\b(?:process|Buffer|document|window)\./.test(source), 'Vendor bundle must run in Apps Script');
assert.ok(!/\b(?:Math\.random|getRandomValues|fetch|randomBytes)\b/.test(source), 'Crypto bundle must not need a random source or external provider');
const license = readFileSync(resolve(packageDir, 'LICENSE'), 'utf8');
const hashesLicense = readFileSync(resolve(hashesDir, 'LICENSE'), 'utf8');
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(resolve(root, 'apps-script/CryptoVendor.gs'), 'utf8'), source, 'Crypto vendor differs from the pinned source. Run npm run crypto:build.');
  assert.equal(readFileSync(resolve(root, 'docs/vendor/noble-ciphers-LICENSE.txt'), 'utf8'), license, 'Crypto vendor license differs from the pinned source.');
  assert.equal(readFileSync(resolve(root, 'docs/vendor/noble-hashes-LICENSE.txt'), 'utf8'), hashesLicense, 'Password vendor license differs from the pinned source.');
} else {
  writeFileSync(resolve(root, 'apps-script/CryptoVendor.gs'), source);
  mkdirSync(resolve(root, 'docs/vendor'), { recursive: true });
  writeFileSync(resolve(root, 'docs/vendor/noble-ciphers-LICENSE.txt'), license);
  writeFileSync(resolve(root, 'docs/vendor/noble-hashes-LICENSE.txt'), hashesLicense);
}
console.log(`Crypto vendor: @noble/ciphers ${metadata.version}, @noble/hashes ${hashesMetadata.version}; ${Buffer.byteLength(source)} bytes; SHA-256 ${createHash('sha256').update(source).digest('hex')}`);
