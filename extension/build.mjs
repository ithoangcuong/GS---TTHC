import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SOURCES } from './adapters/source-registry.mjs';
import { hostPermission, normalizeCentralUrl } from './api/sync.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
await mkdir(path.join(root, 'shared'), { recursive: true });
for (const name of ['registry.mjs', 'normalize.mjs']) await copyFile(path.join(root, '..', 'shared', name), path.join(root, 'shared', name));

// Small deterministic local bundler for named ESM imports/exports used by the isolated content script.
// Each module has its own closure; no external code, eval, cross-world scripts, or web-accessible assets.
const definitions = [], seen = new Map();
async function bundleModule(filename) {
  filename = path.resolve(filename);
  if (seen.has(filename)) return seen.get(filename);
  const id = `module${seen.size}`;
  seen.set(filename, id);
  let code = await readFile(filename, 'utf8');
  const matches = [...code.matchAll(/^import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"];?\s*$/gm)];
  for (const match of matches) {
    if (!match[2].startsWith('.')) throw new Error(`External import not allowed: ${match[2]}`);
    const dependency = await bundleModule(path.resolve(path.dirname(filename), match[2]));
    const bindings = match[1].split(',').map(part => part.trim().replace(/\s+as\s+/, ': ')).join(', ');
    code = code.replace(match[0], `const { ${bindings} } = ${dependency};`);
  }
  const exports = [...code.matchAll(/\bexport\s+(?:async\s+)?(?:const|let|function|class)\s+(\w+)/g)].map(match => match[1]);
  code = code.replace(/\bexport\s+(?=(?:async\s+)?(?:const|let|function|class)\b)/g, '');
  if (/^\s*(?:import|export)\s/m.test(code)) throw new Error(`Unsupported module syntax: ${filename}`);
  definitions.push(`const ${id} = (() => {\n${code}\nreturn { ${exports.join(', ')} };\n})();`);
  return id;
}
await bundleModule(path.join(root, 'content', 'collector.mjs'));
await writeFile(path.join(root, 'content', 'collector.js'), `// Generated by extension/build.mjs; edit .mjs sources.\n(() => {\n'use strict';\n${definitions.join('\n')}\n})();\n`, 'utf8');

const portalMatches = SOURCES.flatMap(source => source.supportedHosts.map(host => `https://${host}/*`));
const extra = process.env.EXTENSION_CENTRAL_ORIGIN ? [hostPermission(normalizeCentralUrl(process.env.EXTENSION_CENTRAL_ORIGIN))] : [];
const legacyOrigin = process.env.EXTENSION_CENTRAL_ORIGIN ? new URL(normalizeCentralUrl(process.env.EXTENSION_CENTRAL_ORIGIN)).origin : null;
const connectSources = [...new Set(['https://script.google.com', 'https://script.googleusercontent.com', legacyOrigin].filter(Boolean))];
const manifest = {
  manifest_version: 3, name: 'Giám sát hồ sơ TTHC — Collector', version: '0.3.0',
  description: 'Collector thủ công, xác nhận đăng nhập và cấu hình nguồn trước khi đọc hồ sơ.',
  minimum_chrome_version: '120', permissions: ['storage', 'activeTab', 'alarms'],
  host_permissions: [...portalMatches, 'https://script.google.com/macros/s/*', 'https://script.googleusercontent.com/*'],
  ...(extra.length ? { optional_host_permissions: [...new Set(extra)] } : {}),
  background: { service_worker: 'background/service-worker.mjs', type: 'module' },
  action: { default_title: 'Collector hồ sơ', default_popup: 'popup/index.html' },
  options_page: 'options/index.html',
  content_scripts: [{ matches: portalMatches, js: ['content/collector.js'], run_at: 'document_idle', all_frames: false, world: 'ISOLATED' }],
  content_security_policy: { extension_pages: `script-src 'self'; object-src 'none'; base-uri 'none'; connect-src ${connectSources.join(' ')};` },
};
await writeFile(path.join(root, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
console.log(`Extension built: ${SOURCES.length} sources, ${portalMatches.length} supplied host names; extractors need configured evidence.`);
